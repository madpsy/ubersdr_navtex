#!/usr/bin/env python3
"""Generate src/navtex_countries.h: country names and flag SVGs for the
operator codes used in src/navtex_stations.h.

    python3 -I tools/gen_navtex_countries.py > src/navtex_countries.h

The station table uses the codes from the Wikipedia list, which are mostly ITU
country codes (MRC Morocco, INS Indonesia, AFS South Africa ...) with a few
territories (ALS Alaska, HWA Hawaii) — not ISO 3166. They are mapped to ISO
alpha-2 here, and the flag for each comes from tools/flags/<iso2>.svg, a copy
of the 4x3 set from flag-icons 7.2.3 (MIT, see tools/flags/LICENSE).

Flags are embedded rather than shown as emoji because Windows renders no
regional-indicator flag glyphs at all, and rather than fetched from a CDN
because a receiver's UI is often viewed on a LAN with no internet.
"""
